// Regenerates src/app/core/build-info.ts with the current package version and build timestamp.
// Run before every build so the UI's status bar reflects what's actually being served — see
// package.json's "build" script, which chains this in automatically.
const fs = require('fs');
const path = require('path');

const pkg = require('../package.json');
const outPath = path.join(__dirname, '../src/app/core/build-info.ts');

const content = `// GENERATED by scripts/generate-build-info.js — do not edit by hand, it is overwritten on every build.
export const BUILD_INFO = {
  version: '${pkg.version}',
  buildTime: '${new Date().toISOString()}',
};
`;

fs.writeFileSync(outPath, content);
console.log(`Wrote ${outPath}`);
